#!/usr/bin/env node
// verify-mood-parity.mjs
//
// TDD guard for the mood-tokens refactor (design: docs/plans/2026-07-22-mood-tokens-design.md).
// After collapsing 16 hand-written `body.cn-*` mood blocks into a single Sass `$moods` map
// generated via `@each`, the compiled `theme.css` must reproduce every mood declaration
// token-for-token. This script locks a golden baseline and fails the build on any drift.
//
//   node scripts/verify-mood-parity.mjs --update   # (re)generate baseline from current theme.css
//   node scripts/verify-mood-parity.mjs            # compare current theme.css against baseline

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const THEME = path.join(ROOT, 'theme.css');
const BASELINE = path.join(ROOT, 'scripts', 'mood-parity-baseline.json');
const UPDATE = process.argv.includes('--update');

// ── Normalisation ───────────────────────────────────────────────────────────
// Collapse whitespace and unify rgb()/hsl() comma vs space syntax so that the
// comparison is robust to CSS minification differences (expanded vs compressed).
function normalize(css) {
  let s = css.replace(/\r?\n/g, ' ').replace(/\s+/g, ' ');
  s = s.replace(/\b(rgb|rgba|hsl|hsla)\(([^)]*)\)/g, (_, fn, args) => {
    return `${fn}(${args.split(',').map((x) => x.trim()).join(' ')})`;
  });
  return s.replace(/\s*([{}:;,])\s*/g, '$1');
}

// ── Extraction ──────────────────────────────────────────────────────────────
// Pull every `body.cn-*` mood rule (light/dark × desktop/mobile variants).
const RULE_RE =
  /body\.cn-[\w-]+(?:\.theme-(?:light|dark))?(?::not\(\.is-mobile\)|\.is-mobile)?\{[^}]*\}/g;

function extract(css) {
  const norm = normalize(css);
  const out = {};
  for (const rule of norm.match(RULE_RE) ?? []) {
    const brace = rule.indexOf('{');
    const selector = rule.slice(0, brace);
    const decls = rule
      .slice(brace + 1, -1)
      .split(';')
      .map((d) => d.trim())
      .filter(Boolean)
      .map((d) => d.replace(/^\s*\/\*.*?\*\/\s*/, '').trim()) // ignore leading /* comment */
      .filter(Boolean)
      .sort();
    // Merge multiple blocks with the same selector (e.g. mood definition + fixup
    // overrides generated by scripts/check-palette-contrast.mjs). Later declarations
    // override earlier ones by property name, matching CSS cascade semantics.
    if (out[selector]) {
      const merged = {};
      for (const d of [...out[selector], ...decls]) {
        const ci = d.indexOf(':');
        if (ci > 0) merged[d.slice(0, ci).trim()] = d;
      }
      out[selector] = Object.values(merged).sort();
    } else {
      out[selector] = decls;
    }
  }
  return out;
}

// ── Main ─────────────────────────────────────────────────────────────────────
if (!fs.existsSync(THEME)) {
  console.error('✗ theme.css not found — run `npm run build` first.');
  process.exit(1);
}
const current = extract(fs.readFileSync(THEME, 'utf8'));
const keys = Object.keys(current).sort();

if (UPDATE) {
  fs.writeFileSync(BASELINE, JSON.stringify(current, null, 2) + '\n');
  console.log(`✓ baseline written: ${keys.length} mood rules captured.`);
  process.exit(0);
}

if (!fs.existsSync(BASELINE)) {
  console.error('✗ baseline missing — run with --update first.');
  process.exit(1);
}
const base = JSON.parse(fs.readFileSync(BASELINE, 'utf8'));
for (const k of Object.keys(base)) {
  base[k] = base[k]
    .map((d) => d.replace(/^\s*\/\*.*?\*\/\s*/, '').trim())
    .filter(Boolean)
    .sort();
}

const baseKeys = Object.keys(base).sort();
const missing = baseKeys.filter((k) => !(k in current));
const extra = keys.filter((k) => !(k in base));
const drift = [];
for (const k of baseKeys) {
  if (!(k in current)) continue;
  const a = base[k];
  const b = current[k];
  const onlyBase = a.filter((d) => !b.includes(d));
  const onlyCurrent = b.filter((d) => !a.includes(d));
  if (onlyBase.length || onlyCurrent.length) {
    drift.push({ selector: k, onlyBase, onlyCurrent });
  }
}

if (missing.length || extra.length || drift.length) {
  console.error('✗ mood parity FAILED — reconstructed CSS diverged from baseline.\n');
  if (missing.length) console.error('  missing rules:\n   - ' + missing.join('\n   - '));
  if (extra.length) console.error('  unexpected new rules:\n   + ' + extra.join('\n   + '));
  for (const d of drift) {
    console.error(`  drift in ${d.selector}:`);
    if (d.onlyBase.length) console.error('    baseline only:\n     ' + d.onlyBase.join('\n     '));
    if (d.onlyCurrent.length) console.error('    current only:\n     ' + d.onlyCurrent.join('\n     '));
  }
  process.exit(1);
}

console.log(`✓ mood parity OK — ${keys.length} mood rules match baseline token-for-token.`);
